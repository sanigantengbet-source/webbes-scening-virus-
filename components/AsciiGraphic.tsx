export default function AsciiGraphic({
  variant = 'bird',
  className = '',
  density = 'normal'
}: AsciiGraphicProps) {
  let asciiContent = ASCII_BIRD_LOGO;
  if (variant === 'bird') asciiContent = ASCII_BIRD_LOGO;
  if (variant === 'malware') asciiContent = ASCII_MALWARE_BUG;
  if (variant === 'virus') asciiContent = ASCII_VIRUS_CELL;
  if (variant === 'skull') asciiContent = ASCII_CYBER_SKULL;
  if (variant === 'shield') asciiContent = ASCII_SHIELD;
  if (variant === 'matrix') asciiContent = ASCII_THREAT_MATRIX;

  const fontSizes = {
    compact: 'text-[5.5px] sm:text-[7.5px] leading-[5.5px] sm:leading-[7.5px]',
    normal: 'text-[6px] xs:text-[7.5px] sm:text-[9px] md:text-[10px] leading-[6.2px] xs:leading-[7.8px] sm:leading-[9.2px] md:leading-[10.2px]',
    large: 'text-[7.5px] sm:text-[11px] leading-[7.5px] sm:leading-[11px]'
  };

  return (
    <pre
      className={`font-mono select-none font-bold text-zinc-900 tracking-tight whitespace-pre overflow-hidden text-center mx-auto ${fontSizes[density]} ${className}`}
      aria-hidden="true"
    >
      {asciiContent}
    </pre>
  );
}
